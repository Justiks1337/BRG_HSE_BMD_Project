"""Независимая от Telegram модель содержимого одного задания бинго.

Постоянные данные задания используются для подписи ячейки и подробной
карточки. Прогресс пользователя хранится отдельно в базе данных.
"""

from dataclasses import dataclass
from io import BytesIO


@dataclass(frozen=True, slots=True)
class BingoTask:
    """Хранит заголовок, изображение и описание задания бинго.

    Общие экземпляры задаются в BINGO_TASKS и не меняются во время работы
    бота. Изображение принимается как BytesIO, включая результат
    AssetsManager.get_assets. Общий буфер используется только для чтения;
    ResponseBuilder создаёт независимый снимок для каждой отправки.

    Attributes:
        title: Короткий заголовок только для ячейки на изображении поля бинго.
        image: Буфер изображения для карточки задания, совместимый с ResponseBuilder.
        description: Подробное описание условий выполнения задания.
    """

    title: str
    image: BytesIO
    description: str
